test("TSE combina cargo, UF, nome único e SQ da candidatura sem exportar informações privadas", () => {
  const code = read("scripts/refresh-dossiers-patrimony.py");
  const ui = read("components/DossieFinanceiroNoticias.tsx");
  assert.match(code, /bem_candidato_\{ano\}\.zip/);
  assert.match(code, /consulta_cand_\{ano\}\.zip/);
  assert.match(code, /len\(ids\) != 1/);
  assert.match(code, /NM_CANDIDATO/);
  assert.match(code, /SQ_CANDIDATO/);
  assert.match(ui, /PATRIMÔNIO DECLARADO AO TSE/);
  assert.match(ui, /Ausência de correspondência não significa patrimônio zero/);
});

test("dossiês têm agendamento central e solicitam deploy único após dados validados", () => {
  const job = read(".github/workflows/atualizar-dossies.yml");
  const site = read(".github/workflows/deploy-visual-fast.yml");
  const news = read(".github/workflows/news-enrichment.yml");
  assert.doesNotMatch(job, /^\s*schedule:/m);
  assert.match(read(".github/workflows/ciclos-dados-ia.yml"), /dispatch atualizar-dossies\.yml/);
  assert.match(job, /permissions:\s*\n\s*contents: write/);
  assert.match(job, /secrets\.GEMINI_API_KEY/);
  assert.match(job, /snapshot legislativo verificado/);
  assert.match(news, /npx tsx scripts\/refresh-dossiers-news\.ts/);
  assert.match(news, /tests\/agruparNoticias\.test\.ts/);
  assert.match(news, /gh workflow run deploy-visual-fast\.yml/);
  assert.doesNotMatch(news, /^\s*schedule:/m);
  assert.match(read(".github/workflows/ciclos-dados-ia.yml"), /dispatch news-enrichment\.yml/);
  assert.match(job, /python scripts\/refresh-dossiers-patrimony\.py/);
  assert.match(job, /python -I scripts\/publish-dossiers-safe\.py/);
  assert.doesNotMatch(job, /git rebase origin\/main/);
  assert.match(job, /ruido-dossies-verificados/);
  assert.match(job, /gh workflow run deploy-visual-fast\.yml/);
  const datajud = read(".github/workflows/enriquecer-datajud.yml");
  
  assert.match(datajud, /python scripts\/refresh-dossiers-datajud\.py/);
  assert.match(datajud, /python -I scripts\/publish-dossiers-safe\.py public\/data\/dossies\/datajud\.json/);
  assert.doesNotMatch(datajud, /git pull --rebase origin main/);
  assert.match(job, /public\/data\/dossies\/financeiro\.json/);
  assert.match(job, /public\/data\/dossies\/patrimonio\.json/);
  assert.doesNotMatch(job, /git add .*datajud\.json/);
  assert.doesNotMatch(job, /git add .*noticias\.json/);
  assert.match(news, /python -I scripts\/publish-collector-safe\.py news/);
  assert.doesNotMatch(news, /git rebase origin\/main/);
  const finance = read(".github/workflows/financial-links.yml");
  assert.match(finance, /python -I scripts\/publish-collector-safe\.py finance/);
  assert.doesNotMatch(finance, /git rebase origin\/main/);
  assert.doesNotMatch(datajud, /git add .*noticias\.json/);
  assert.doesNotMatch(news, /git add .*datajud\.json/);
  assert.match(site, /push:\s*\n\s*branches: \[main\]/);
  assert.match(site, /schedule:/);
  assert.doesNotMatch(site, /actions\/(?:upload|download)-artifact@/);
  assert.match(site, /scripts\/audit-public-export\.py out/);
  assert.match(site, /git -C "\$dest" push origin HEAD:main/);
  assert.match(site, /cancel-in-progress: true/);
  assert.match(site, /if: steps\.freshness\.outputs\.current == 'true'/);
  assert.doesNotMatch(site, /^  workflow_run:/m);
});
