import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = (path: string) => readFileSync(path, "utf8");
test("todos os perfis possuem interface financeira e de notícia sem token de API no cliente", () => {
  const page = read("app/parlamentares/[id]/page.tsx");
  const panel = read("components/DossieFinanceiroNoticias.tsx");
  assert.match(page, /<DossieFinanceiroNoticias/);
  assert.match(panel, /financeiro\.json/);
  assert.match(panel, /patrimonio\.json/);
  assert.match(panel, /noticias\.json/);
  assert.match(panel, /new Set\(x\.fontes\.map\(y => y\.grupoEditorial\)\)\.size === x\.fontes\.length/);
  assert.match(panel, /FONTE_UNICA/);
  assert.match(panel, /COBERTURA JORNALÍSTICA/);
  assert.match(panel, /const validade = 180 \* 24 \* 60 \* 60 \* 1000/);
  assert.match(panel, /avisoReconferencia = 45 \* 24 \* 60 \* 60 \* 1000/);
  assert.match(panel, /ARQUIVO DE REPORTAGENS/);
  assert.match(panel, /clippings/);
  assert.match(panel, /Não há valores consolidados verificados/);
  assert.match(panel, /nenhuma classificação como investigado/);
  assert.doesNotMatch(panel, /GEMINI_API_KEY|fetch\(/);
});
